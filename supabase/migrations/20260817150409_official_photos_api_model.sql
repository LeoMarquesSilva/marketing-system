CREATE OR REPLACE VIEW public.official_system_photos
WITH (security_invoker = true)
AS
SELECT
  u.id AS user_id,
  u.name,
  u.email,
  lower(trim(u.email)) AS normalized_email,
  selected.photo_id,
  COALESCE(selected.public_url, u.avatar_url) AS photo_url,
  CASE
    WHEN selected.photo_id IS NOT NULL THEN 'selected'
    WHEN u.avatar_url IS NOT NULL THEN 'legacy_avatar'
    ELSE 'none'
  END AS source,
  COALESCE(selected.updated_at, u.updated_at, now()) AS updated_at,
  md5(
    COALESCE(selected.public_url, u.avatar_url, '')
    || ':'
    || COALESCE(selected.updated_at, u.updated_at, now())::text
  ) AS version
FROM public.users u
LEFT JOIN LATERAL (
  SELECT
    cp.id AS photo_id,
    cp.public_url,
    cpu.updated_at
  FROM public.collaborator_photo_usages cpu
  JOIN public.photo_usage_types put
    ON put.id = cpu.usage_type_id
   AND put.is_official = true
  JOIN public.collaborator_photos cp
    ON cp.id = cpu.photo_id
   AND cp.user_id = cpu.user_id
  WHERE cpu.user_id = u.id
  LIMIT 1
) selected ON true
WHERE u.is_active IS NOT FALSE;

REVOKE ALL ON TABLE public.official_system_photos FROM anon, authenticated;
GRANT SELECT ON TABLE public.official_system_photos TO service_role;

CREATE OR REPLACE FUNCTION public.consume_official_photo_api_quota(p_consumer_id uuid)
RETURNS boolean
LANGUAGE plpgsql
VOLATILE
SET search_path = ''
AS $$
DECLARE
  current_window timestamptz := date_trunc('minute', now());
  allowed_limit integer;
  current_count integer;
BEGIN
  SELECT c.rate_limit_per_minute
    INTO allowed_limit
  FROM public.official_photo_api_consumers c
  WHERE c.id = p_consumer_id
    AND c.is_active = true;

  IF allowed_limit IS NULL THEN
    RETURN false;
  END IF;

  INSERT INTO public.official_photo_api_rate_limits (
    consumer_id,
    window_start,
    request_count
  )
  VALUES (p_consumer_id, current_window, 1)
  ON CONFLICT (consumer_id, window_start)
  DO UPDATE SET request_count =
    public.official_photo_api_rate_limits.request_count + 1
  RETURNING request_count INTO current_count;

  RETURN current_count <= allowed_limit;
END;
$$;

REVOKE ALL ON FUNCTION public.consume_official_photo_api_quota(uuid)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.consume_official_photo_api_quota(uuid)
  TO service_role;

