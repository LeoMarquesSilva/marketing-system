CREATE TABLE public.official_photo_api_consumers (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  slug text NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9][a-z0-9-]{1,62}$'),
  name text NOT NULL,
  key_prefix text UNIQUE,
  key_hash text UNIQUE CHECK (key_hash IS NULL OR key_hash ~ '^[0-9a-f]{64}$'),
  allowed_scopes text[] NOT NULL DEFAULT ARRAY['photos:read']::text[],
  rate_limit_per_minute integer NOT NULL DEFAULT 300
    CHECK (rate_limit_per_minute BETWEEN 1 AND 10000),
  is_active boolean NOT NULL DEFAULT true,
  key_rotated_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.official_photo_system_links (
  consumer_id uuid NOT NULL
    REFERENCES public.official_photo_api_consumers(id) ON DELETE CASCADE,
  external_user_id text NOT NULL CHECK (length(trim(external_user_id)) > 0),
  user_id uuid NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (consumer_id, external_user_id),
  UNIQUE (consumer_id, user_id)
);

CREATE INDEX official_photo_system_links_user_id_idx
  ON public.official_photo_system_links(user_id);

CREATE TABLE public.official_photo_api_requests (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  consumer_id uuid
    REFERENCES public.official_photo_api_consumers(id) ON DELETE SET NULL,
  route text NOT NULL,
  method text NOT NULL,
  status_code integer NOT NULL CHECK (status_code BETWEEN 100 AND 599),
  latency_ms integer NOT NULL CHECK (latency_ms >= 0),
  lookup_count integer NOT NULL DEFAULT 0 CHECK (lookup_count >= 0),
  requested_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX official_photo_api_requests_consumer_requested_idx
  ON public.official_photo_api_requests(consumer_id, requested_at DESC);

CREATE TABLE public.official_photo_api_rate_limits (
  consumer_id uuid NOT NULL
    REFERENCES public.official_photo_api_consumers(id) ON DELETE CASCADE,
  window_start timestamptz NOT NULL,
  request_count integer NOT NULL DEFAULT 0 CHECK (request_count >= 0),
  PRIMARY KEY (consumer_id, window_start)
);

